export function getCurrentDhakaMonthLabel(locale: Locale): string {
  const nowDhaka = new Date(Date.now() + 6 * 60 * 60 * 1000);
  return new Intl.DateTimeFormat(locale === "bn" ? "bn-BD" : "en-US", {
    month: "long",
    year: "numeric",
    timeZone: "UTC"
  }).format(nowDhaka);
}
